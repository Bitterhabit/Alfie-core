#!/usr/bin/env bash
set -Eeuo pipefail

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT_DIR"

COMPOSE=(docker compose -f compose.yaml -f compose.local.yaml)

usage() {
  cat <<'EOF'
Alfie Core installer

Usage:
  sudo ./install.sh          First installation
  sudo ./install.sh --upgrade  Update the checkout and rebuild without deleting data
  ./install.sh --help

First install creates private credentials and local configuration, validates
Compose, builds both services, and waits for their health checks.
EOF
}

fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
info() { printf '\n==> %s\n' "$*"; }

case "${1:-}" in
  --help|-h) usage; exit 0 ;;
  --upgrade)
    [[ -f .env ]] || fail "No .env found. Run ./install.sh for first-time setup."
    [[ -f compose.local.yaml ]] || fail "compose.local.yaml is missing; refusing to guess local settings."
    command -v docker >/dev/null 2>&1 || fail "Docker is required."
    docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 is required."
    docker info >/dev/null 2>&1 || fail "Docker is unavailable or this user cannot access the Docker daemon."
    info "Updating source from origin/main"
    git pull --ff-only origin main
    info "Validating existing local configuration"
    "${COMPOSE[@]}" config --quiet
    info "Building and updating Alfie without deleting persistent volumes"
    "${COMPOSE[@]}" up -d --build --wait --wait-timeout 180
    "${COMPOSE[@]}" ps
    printf '\nUpgrade complete. Persistent volumes were not removed.\n'
    exit 0
    ;;
  "") ;;
  *) usage; fail "Unknown option: $1" ;;
esac

[[ ! -e .env ]] || fail ".env already exists. Refusing to overwrite credentials. Use ./install.sh --upgrade for a non-destructive update."
[[ ! -e compose.local.yaml ]] || fail "compose.local.yaml already exists. Move it aside or review it before first install."
[[ -f .env.example && -f compose.yaml ]] || fail "Run this installer from the Alfie Core repository root."

command -v docker >/dev/null 2>&1 || fail "Docker is required. Install Docker Engine and the Compose v2 plugin first."
command -v openssl >/dev/null 2>&1 || fail "OpenSSL is required to generate credentials."
command -v curl >/dev/null 2>&1 || fail "curl is required for health checks."
docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 is required."
docker info >/dev/null 2>&1 || fail "Docker is unavailable or this user cannot access the Docker daemon."

printf 'Alfie Core — first-time installation\n'
printf 'This installs the independent Core and Interface. It does not install or modify Petrio.\n\n'

DEFAULT_ORIGIN="https://alfie.petrio-house.co.uk"
read -r -p "Public HTTPS origin [$DEFAULT_ORIGIN]: " PUBLIC_ORIGIN
PUBLIC_ORIGIN="${PUBLIC_ORIGIN:-$DEFAULT_ORIGIN}"
[[ "$PUBLIC_ORIGIN" =~ ^https://[A-Za-z0-9.-]+(:[0-9]{1,5})?$ ]] || fail "Enter an HTTPS origin such as https://alfie.example.com (no path or trailing slash)."

DEFAULT_BIND="127.0.0.1"
read -r -p "Host bind address for the Interface [$DEFAULT_BIND]: " BIND_ADDRESS
BIND_ADDRESS="${BIND_ADDRESS:-$DEFAULT_BIND}"
[[ "$BIND_ADDRESS" == "127.0.0.1" || "$BIND_ADDRESS" == "0.0.0.0" || "$BIND_ADDRESS" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || fail "Enter 127.0.0.1, 0.0.0.0, or an IPv4 address."
read -r -p "Host port for the Interface [8781]: " HOST_PORT
HOST_PORT="${HOST_PORT:-8781}"
[[ "$HOST_PORT" =~ ^[0-9]+$ ]] && (( HOST_PORT >= 1 && HOST_PORT <= 65535 )) || fail "Port must be between 1 and 65535."

info "Generating fresh private credentials"
SERVICE_TOKEN="$(openssl rand -hex 32)"
IDENTITY_SECRET="$(openssl rand -hex 32)"
cp .env.example .env
chmod 600 .env

write_env() {
  local key="$1" value="$2"
  if grep -q "^$key=" .env; then
    sed -i "s|^$key=.*|$key=$value|" .env
  else
    printf '%s=%s\n' "$key" "$value" >> .env
  fi
}
write_env ALFIE_CORE_SERVICE_TOKEN "$SERVICE_TOKEN"
write_env ALFIE_CORE_STANDALONE_IDENTITY_SECRET "$IDENTITY_SECRET"
write_env ALFIE_UI_PUBLIC_ORIGIN "$PUBLIC_ORIGIN"
write_env ALFIE_UI_COOKIE_SECURE "true"
unset SERVICE_TOKEN IDENTITY_SECRET

cat > compose.local.yaml <<EOF
# Generated by install.sh. Keep this file local; it is host-specific.
services:
  alfie-interface:
    ports:
      - "${BIND_ADDRESS}:${HOST_PORT}:8781"
EOF
chmod 600 compose.local.yaml

info "Validating generated configuration"
"${COMPOSE[@]}" config --quiet

info "Building and starting Alfie Core and Interface"
"${COMPOSE[@]}" up -d --build --wait --wait-timeout 180

info "Checking service health"
CHECK_HOST="$BIND_ADDRESS"
[[ "$CHECK_HOST" == "0.0.0.0" ]] && CHECK_HOST="127.0.0.1"
curl --fail --silent --show-error "http://$CHECK_HOST:$HOST_PORT/health" >/dev/null || fail "Interface health endpoint did not respond locally."
"${COMPOSE[@]}" ps

printf '\nInstallation complete.\n'
printf 'Interface (local): http://127.0.0.1:%s\n' "$HOST_PORT"
if [[ "$BIND_ADDRESS" != "127.0.0.1" ]]; then
  printf 'Interface (bound): http://%s:%s\n' "$BIND_ADDRESS" "$HOST_PORT"
fi
printf 'Configured public origin: %s\n' "$PUBLIC_ORIGIN"
printf 'Open the public origin after your trusted HTTPS reverse proxy/tunnel is configured.\n'
printf 'Create the first administrator using the one-time setup form. No default password was created.\n'
printf '\nCredentials are stored in .env (mode 600). Do not commit or share that file.\n'
printf 'For future updates run: sudo ./install.sh --upgrade\n'
